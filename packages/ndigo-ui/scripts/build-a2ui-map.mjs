#!/usr/bin/env node
/**
 * Generates the A2UI component map from the registry.
 *
 * Only `registry:ui` items that ship a custom-element implementation (`nd-*.ts`)
 * are renderable A2UI components; native-first styling items (CSS only) are not
 * components and are excluded. The emitted map is committed and installed with
 * the `a2ui-surface` registry item.
 *
 * Usage:
 *   node packages/ndigo-ui/scripts/build-a2ui-map.mjs          # write
 *   node packages/ndigo-ui/scripts/build-a2ui-map.mjs --check  # verify
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const REGISTRY = join(PACKAGE_ROOT, 'registry.json');
const OUTPUTS = [
    join(PACKAGE_ROOT, 'registry', 'ui', 'a2ui-surface', 'component-map.ts'),
    // The lab owns a copy that stays in sync with the registry-generated map;
    // `--check` verifies both identities the same way.
    join(PACKAGE_ROOT, '..', '..', 'apps', '20-ndigo-ui-lab', 'src', 'ui', 'nd-a2ui-surface', 'component-map.ts'),
];
const CHECK = process.argv.includes('--check');

const registry = JSON.parse(readFileSync(REGISTRY, 'utf8'));

const componentName = (name) =>
    name
        .split(/[-_]/u)
        .filter(Boolean)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');

const entries = [];
for (const item of registry.items ?? []) {
    if (item.type !== 'registry:ui') continue;
    // The surface is the renderer, not one of its own components.
    if (item.name === 'a2ui-surface') continue;
    const elementFile = (item.files ?? [])
        .map((file) => file.path)
        .find((path) => typeof path === 'string' && /\/nd-[a-z0-9-]+\.ts$/u.test(path));
    if (elementFile === undefined) continue;
    const tag = elementFile.split('/').pop().replace(/\.ts$/u, '');
    entries.push([componentName(item.name), tag]);
}
entries.sort(([left], [right]) => left.localeCompare(right));

const propertyKey = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(name) ? name : `'${name}'`);

const content = `/**
 * Generated by packages/ndigo-ui/scripts/build-a2ui-map.mjs — do not edit.
 *
 * A2UI component name → ndigo-ui custom element. Only registry:ui items with a
 * custom-element implementation are renderable; native-first items are CSS-only
 * and deliberately absent. The surface filters this map to elements the
 * application defines, so the A2UI vocabulary is the installed set.
 */
export const COMPONENT_ELEMENTS: Readonly<Record<string, string>> = {
${entries.map(([name, tag]) => `    ${propertyKey(name)}: '${tag}',`).join('\n')}
};
`;

if (CHECK) {
    if (OUTPUTS.some((target) => !existsSync(target) || readFileSync(target, 'utf8') !== content)) {
        process.stderr.write('✗ a2ui map is stale — run `pnpm ui:a2ui-map:build`\n');
        process.exitCode = 1;
    } else {
        console.log(`a2ui map current (${entries.length} components)`);
    }
} else {
    for (const target of OUTPUTS) {
        writeFileSync(target, content, 'utf8');
    }
    console.log(`a2ui map: ${entries.length} components`);
}
