/**
 * Root-tooling lane for the consumer agent content: the per-package
 * `docs/llms.txt` export index, the skill frontmatter `package` field, and
 * the direct-dependency read paths an installed application relies on.
 *
 * Runs under `pnpm test:tooling` (`node --test` — no vitest, no nx). The name
 * deliberately escapes vitest's `*.test.*` glob.
 */
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

import { collectPublicExports, renderPackageIndex } from '../tools/agent-content/_package-index.mjs';
import {
    capabilityProblems,
    readCapabilityCatalog,
    renderCapabilityLine,
} from '../tools/agent-content/_capabilities.mjs';
import { readSkills } from '../tools/agent-content/_skills.mjs';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

/** Creates a throwaway skills tree with one probe skill. */
function fixtureSkills(packageLine) {
    const root = mkdtempSync(join(tmpdir(), 'ndigo-skills-'));
    mkdirSync(join(root, 'probe-skill'));
    const frontmatter = [
        '---',
        'name: probe-skill',
        'description: Probe skill.',
        packageLine,
        '---',
        '',
        '# Probe',
        '',
    ].join('\n');
    writeFileSync(join(root, 'probe-skill', 'SKILL.md'), frontmatter, 'utf8');
    return root;
}

void test('a quoted package frontmatter field is accepted and returned', () => {
    const root = fixtureSkills('package: "@ndigo/ui"');
    try {
        const [skill] = readSkills(root);
        assert.equal(skill.package, '@ndigo/ui');
    } finally {
        rmSync(root, { recursive: true, force: true });
    }
});

void test('a missing package frontmatter field stays undefined', () => {
    const root = fixtureSkills('');
    try {
        const [skill] = readSkills(root);
        assert.equal(skill.package, undefined);
    } finally {
        rmSync(root, { recursive: true, force: true });
    }
});

void test('a package frontmatter field outside @ndigo/<name> is rejected', () => {
    const root = fixtureSkills('package: ndigo-ui');
    try {
        assert.throws(() => readSkills(root), /expected @ndigo\/<lower-case-name>/u);
    } finally {
        rmSync(root, { recursive: true, force: true });
    }
});

void test('a non-lower-case package name is rejected', () => {
    const root = fixtureSkills('package: "@ndigo/UI"');
    try {
        assert.throws(() => readSkills(root), /expected @ndigo\/<lower-case-name>/u);
    } finally {
        rmSync(root, { recursive: true, force: true });
    }
});

void test('the @ndigo/core index resolves named, star, and documented exports', () => {
    const entries = collectPublicExports(join(ROOT, 'packages', 'ndigo-core', 'src', 'index.ts'));
    assert.ok(entries.length >= 50, `expected a substantial export list, got ${entries.length}`);
    assert.ok(entries.some((entry) => entry.name === 'MediaTypes'));
    assert.ok(entries.some((entry) => entry.name === 'IllegalStateError'));
    assert.ok(entries.filter((entry) => typeof entry.doc === 'string').length >= 10);
    assert.ok(entries.every((entry) => /^[A-Za-z_$][\w$]*$/u.test(entry.name)));
});

void test('the rendered package index carries the header, subpaths, and exports', () => {
    const root = join(ROOT, 'packages', 'ndigo-core');
    const text = renderPackageIndex({ root, manifest: JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) });
    assert.match(text, /^<!-- Generated by tools\/agent-content\/build\.mjs/u);
    assert.match(text, /# @ndigo\/core/u);
    assert.match(text, /## Public exports/u);
    assert.match(text, /- `MediaTypes`/u);
});

void test('the rendered package index carries composed capabilities', () => {
    const root = join(ROOT, 'packages', 'ndigo-mcp');
    const entry = {
        id: 'agent-surface',
        kind: 'capability',
        summary: 'Probe capability.',
        packages: ['@ndigo/mcp'],
        guide: '48-agent-facing-surfaces',
        ops: [],
        checks: [],
    };
    const text = renderPackageIndex({
        root,
        manifest: JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')),
        capabilities: [entry],
    });
    assert.match(text, /## Capabilities/u);
    assert.ok(text.includes(renderCapabilityLine(entry)));
});

/** Reads every workspace package manifest the generator sees. */
function workspacePackages() {
    return readdirSync(join(ROOT, 'packages'))
        .filter((entry) => existsSync(join(ROOT, 'packages', entry, 'package.json')))
        .map((entry) => ({
            root: join(ROOT, 'packages', entry),
            manifest: JSON.parse(readFileSync(join(ROOT, 'packages', entry, 'package.json'), 'utf8')),
        }))
        .sort((left, right) => left.manifest.name.localeCompare(right.manifest.name));
}

void test('the shipped capability catalog passes reference integrity', () => {
    const catalogDir = join(ROOT, 'packages', 'ndigo-cli', 'assets', 'capabilities');
    const catalog = readCapabilityCatalog(catalogDir);
    assert.deepEqual(catalog.errors, []);
    const problems = capabilityProblems({
        root: ROOT,
        catalogDir,
        catalog,
        packages: workspacePackages(),
        skills: readSkills(join(ROOT, 'tools', 'agent-content', 'skills')),
    });
    assert.deepEqual(problems, []);
});

void test('a capability naming an unknown package fails validation', () => {
    const catalogDir = join(ROOT, 'packages', 'ndigo-cli', 'assets', 'capabilities');
    const catalog = readCapabilityCatalog(catalogDir);
    const [first] = catalog.capabilities;
    const broken = {
        ...catalog,
        capabilities: [{ ...first, packages: ['@ndigo/not-a-package'] }],
    };
    const problems = capabilityProblems({
        root: ROOT,
        catalogDir,
        catalog: broken,
        packages: workspacePackages(),
        skills: readSkills(join(ROOT, 'tools', 'agent-content', 'skills')),
    });
    assert.ok(
        problems.some((problem) => problem.includes('names unknown package "@ndigo/not-a-package"')),
        problems.join('; ')
    );
});

void test('a direct dependency exposes the installed llms.txt through node_modules', () => {
    const index = join(ROOT, 'apps', '05-ndigo-api', 'node_modules', '@ndigo', 'core', 'docs', 'llms.txt');
    assert.ok(existsSync(index), `expected ${index}; run pnpm install and pnpm agent-content:build`);
    const text = readFileSync(index, 'utf8');
    assert.ok(text.length > 0);
    assert.match(text, /@ndigo\/core/u);
});

void test('a direct dependency exposes the packaged skill fallback through node_modules', () => {
    const skill = join(
        ROOT,
        'apps',
        '20-ndigo-ui-lab',
        'node_modules',
        '@ndigo',
        'ui',
        'skills',
        'ndigo-ui',
        'SKILL.md'
    );
    assert.ok(existsSync(skill), `expected ${skill}; run pnpm install and pnpm agent-content:build`);
    assert.match(readFileSync(skill, 'utf8'), /name: ndigo-ui/u);
});
