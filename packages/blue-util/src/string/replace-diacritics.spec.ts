        expect(replaceDiacritics('ô')).toBe('o');
        expect(replaceDiacritics('õ')).toBe('o');
        expect(replaceDiacritics('ö')).toBe('o');
        expect(replaceDiacritics('ø')).toBe('o');
        expect(replaceDiacritics('ù')).toBe('u');
