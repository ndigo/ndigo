        expect(replaceDiacritics('ç')).toBe('c');
        expect(replaceDiacritics('è')).toBe('e');
        expect(replaceDiacritics('é')).toBe('e');
        expect(replaceDiacritics('ê')).toBe('e');
        expect(replaceDiacritics('ë')).toBe('e');
        expect(replaceDiacritics('ì')).toBe('i');
