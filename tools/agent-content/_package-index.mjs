/**
 * Cheap, deterministic inputs for the per-package `docs/llms.txt` index.
 *
 * The index is generated from committed, authored inputs only — the package
 * manifest, its README (presence), and the `src/index.ts` re-export graph — so
 * generation never depends on a TypeScript build or a TypeDoc run, and the
 * agent-content drift check stays inside the ordinary CI lane.
 */
import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { renderCapabilityLine } from './_capabilities.mjs';

/**
 * Re-export following stays shallow: the index orients an agent on the public
 * surface of the installed package, it does not enumerate the module graph.
 */
const MAX_REEXPORT_DEPTH = 4;

/** One-line doc extraction stops here so an entry never wraps. */
const MAX_DOC_LENGTH = 160;

const namedFromPattern = /export\s+(type\s+)?\{([\s\S]*?)\}\s+from\s+['"]([^'"]+)['"]/gu;
const starFromPattern = /export\s+\*\s+from\s+['"]([^'"]+)['"]/gu;
const starAsPattern = /export\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\s+['"]([^'"]+)['"]/gu;
const localExportPattern = /export\s+(type\s+)?\{([^}]*)\}(?!\s*from\b)/gu;
const declarationPattern =
    /^export\s+(?:declare\s+)?(?:(?:abstract|async)\s+)*(class|interface|type|function|const|let|var|enum)\*?\s+([A-Za-z_$][\w$]*)/gmu;
const defaultExportPattern = /^export\s+default\s+([A-Za-z_$][\w$]*)/gmu;

/**
 * Renders the `docs/llms.txt` index for one workspace package.
 *
 * @param pkg - `{ root, manifest }` for the package directory.
 * @returns The full index text, newline-terminated.
 */
export function renderPackageIndex(pkg) {
    const { manifest, root } = pkg;
    const entry = join(root, 'src', 'index.ts');
    const exports = existsSync(entry) ? dedupe(collectPublicExports(entry)) : [];
    const subpaths = Object.keys(manifest.exports ?? {}).filter((key) => key !== '.' && key !== './package.json');
    const capabilities = Array.isArray(pkg.capabilities) ? pkg.capabilities : [];

    const lines = ['<!-- Generated by tools/agent-content/build.mjs — do not edit. -->', `# ${manifest.name}`, ''];
    if (typeof manifest.description === 'string' && manifest.description !== '') lines.push(manifest.description, '');
    lines.push(
        'Version-matched export index for the installed package. Read `README.md`',
        'for usage; the workspace guide index ships with `@ndigo/cli` as',
        '`assets/agent/docs-index.md`.',
        ''
    );
    if (subpaths.length > 0) {
        lines.push('## Subpaths', '', ...subpaths.map((subpath) => `- \`${manifest.name}${subpath.slice(1)}\``), '');
    }
    if (capabilities.length > 0) {
        lines.push('## Capabilities', '', ...capabilities.map(renderCapabilityLine), '');
    }
    lines.push('## Public exports', '');
    if (exports.length === 0) {
        lines.push('- (none resolved from `src/index.ts`)');
    } else {
        lines.push(...exports.map(formatExport));
    }
    lines.push('');
    return lines.join('\n');
}

/**
 * Collects public exports from an entry file, following relative re-exports.
 *
 * @param entry - Absolute path to the package's `src/index.ts`.
 * @returns Export entries in source order, duplicates included.
 */
export function collectPublicExports(entry) {
    return collectFile(entry, { depth: 0, seen: new Set(), cache: new Map() });
}

function formatExport(entry) {
    const marker = entry.typeOnly ? ' *(type)*' : '';
    const doc = entry.doc === undefined ? '' : ` — ${entry.doc}`;
    return `- \`${entry.name}\`${marker}${doc}`;
}

function dedupe(entries) {
    const byName = new Map();
    for (const entry of entries) {
        if (!byName.has(entry.name)) byName.set(entry.name, entry);
    }
    return [...byName.values()];
}

function collectFile(file, context) {
    if (context.depth > MAX_REEXPORT_DEPTH || context.seen.has(file)) return [];
    context.seen.add(file);
    const text = readCached(file, context.cache);
    if (text === null) return [];
    const statements = [];
    for (const match of text.matchAll(namedFromPattern)) {
        statements.push({
            at: match.index,
            kind: 'named',
            names: parseNames(match[2], match[1] !== undefined),
            spec: match[3],
        });
    }
    for (const match of text.matchAll(starFromPattern)) {
        statements.push({ at: match.index, kind: 'star', spec: match[1] });
    }
    for (const match of text.matchAll(starAsPattern)) {
        statements.push({ at: match.index, kind: 'decl', name: match[1], typeOnly: false });
    }
    for (const match of text.matchAll(localExportPattern)) {
        statements.push({
            at: match.index,
            kind: 'named',
            names: parseNames(match[2], match[1] !== undefined),
        });
    }
    for (const match of text.matchAll(declarationPattern)) {
        statements.push({
            at: match.index,
            kind: 'decl',
            name: match[2],
            typeOnly: match[1] === 'interface' || match[1] === 'type',
        });
    }
    for (const match of text.matchAll(defaultExportPattern)) {
        statements.push({ at: match.index, kind: 'decl', name: 'default', typeOnly: false });
    }
    statements.sort((left, right) => left.at - right.at);

    const entries = [];
    for (const statement of statements) {
        if (statement.kind === 'named') {
            const target = statement.spec === undefined ? null : resolveModule(file, statement.spec);
            const targetDocs = target === null ? null : docsIn(target, context);
            for (const { name, typeOnly } of statement.names) {
                const found = targetDocs?.get(name);
                entries.push({
                    name,
                    typeOnly: typeOnly || found?.typeOnly === true,
                    doc: found?.doc,
                });
            }
        } else if (statement.kind === 'star') {
            const target = resolveModule(file, statement.spec);
            if (target !== null) entries.push(...collectFile(target, { ...context, depth: context.depth + 1 }));
        } else {
            entries.push({ name: statement.name, typeOnly: statement.typeOnly, doc: precedingDoc(text, statement.at) });
        }
    }
    return entries;
}

function readCached(file, cache) {
    if (cache.has(file)) return cache.get(file);
    let text = null;
    try {
        if (statSync(file).isFile()) text = readFileSync(file, 'utf8');
    } catch {
        text = null;
    }
    cache.set(file, text);
    return text;
}

/** Maps every declaration name in a file to its doc snippet, for one lookup level. */
function docsIn(file, context) {
    const text = readCached(file, context.cache);
    if (text === null) return null;
    const map = new Map();
    for (const match of text.matchAll(declarationPattern)) {
        map.set(match[2], {
            typeOnly: match[1] === 'interface' || match[1] === 'type',
            doc: precedingDoc(text, match.index),
        });
    }
    return map;
}

/**
 * Resolves a relative `.js`-style specifier to the committed TypeScript source.
 *
 * @param fromFile - The importing file.
 * @param spec - The raw specifier; external packages resolve to null.
 * @returns The resolved source path, or null when it cannot be resolved.
 */
function resolveModule(fromFile, spec) {
    if (!spec.startsWith('.')) return null;
    const base = join(dirname(fromFile), spec);
    const candidates = [
        base.replace(/\.js$/u, '.ts').replace(/\.jsx$/u, '.tsx'),
        `${base}.ts`,
        `${base}.tsx`,
        join(base, 'index.ts'),
    ];
    return (
        candidates.find((candidate) => {
            try {
                return statSync(candidate).isFile();
            } catch {
                return false;
            }
        }) ?? null
    );
}

function parseNames(source, statementTypeOnly) {
    const names = [];
    for (let entry of source.split(',')) {
        entry = entry.trim();
        if (entry === '') continue;
        let typeOnly = statementTypeOnly;
        if (/^type\s+/u.test(entry)) {
            typeOnly = true;
            entry = entry.replace(/^type\s+/u, '');
        }
        const name = entry
            .split(/\s+as\s+/u)
            .at(-1)
            ?.trim();
        if (name === undefined || !/^[A-Za-z_$][\w$]*$/u.test(name)) continue;
        names.push({ name, typeOnly });
    }
    return names;
}

/**
 * Reads the JSDoc paragraph immediately above a declaration.
 *
 * @param text - The file text.
 * @param index - The declaration's match index.
 * @returns The collapsed first paragraph, or undefined without a doc block.
 */
function precedingDoc(text, index) {
    const before = text.slice(0, index);
    const close = before.lastIndexOf('*/');
    if (close === -1 || before.slice(close + 2).trim() !== '') return undefined;
    const open = before.lastIndexOf('/*', close);
    if (open === -1 || !before.startsWith('/**', open)) return undefined;
    const lines = [];
    for (const raw of before.slice(open + 3, close).split('\n')) {
        const line = raw.replace(/^\s*\* ?/u, '').trim();
        if (line === '') {
            if (lines.length > 0) break;
            continue;
        }
        if (line.startsWith('@')) break;
        lines.push(line);
    }
    if (lines.length === 0) return undefined;
    const doc = lines
        .join(' ')
        .replace(/\s+/gu, ' ')
        .replace(/\{@link(?:code)?\s+([^\s}|]+)[^}]*\}/gu, '$1')
        .trim();
    return doc.length > MAX_DOC_LENGTH ? `${doc.slice(0, MAX_DOC_LENGTH - 1).trimEnd()}…` : doc;
}
