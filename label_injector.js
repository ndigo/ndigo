function main() {
    if (!fs.existsSync(GRAPH_PATH)) {
        console.error(`Error: ${GRAPH_PATH} not found`);
        process.exit(1);
    }

    const data = JSON.parse(fs.readFileSync(GRAPH_PATH, 'utf8'));
    const nodes = data.nodes || [];
    let count = 0;

    for (const node of nodes) {
        const cid = node.community;
        if (cid !== undefined) {
            const label = LABELS[cid] || `Community ${cid}`;
            node.community_label = label;
            if (label !== `Community ${cid}`) {
                count++;
            }
        }
    }

    fs.writeFileSync(GRAPH_PATH, JSON.stringify(data, null, 2), 'utf8');
    console.log(`Successfully injected labels for ${count} nodes across ${Object.keys(LABELS).length} communities.`);
}

main();
